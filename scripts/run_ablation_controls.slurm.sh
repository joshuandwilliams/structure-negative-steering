#!/bin/bash
#SBATCH --job-name="nf_ablation"
#SBATCH -p jic-medium
#SBATCH -N 1
#SBATCH -n 1
#SBATCH -c 2
#SBATCH --mem=4G
#SBATCH --time=24:00:00
#SBATCH --output=nf_ablation_%j.out
#SBATCH --error=nf_ablation_%j.err
#SBATCH --mail-type=END,FAIL
#SBATCH --mail-user=jowillia@nbi.ac.uk
# ─────────────────────────────────────────────────────────────────────────────
# run_ablation_controls.slurm.sh — the interface-ablation controls, as one batch job.
#
#   sbatch scripts/run_ablation_controls.slurm.sh smoke_scrambled_restrained
#   sbatch scripts/run_ablation_controls.slurm.sh smoke_scrambled_unrestrained
#   sbatch scripts/run_ablation_controls.slurm.sh scrambled_restrained    # all 18
#   sbatch scripts/run_ablation_controls.slurm.sh scrambled_unrestrained  # all 18
#   sbatch scripts/run_ablation_controls.slurm.sh all                     # everything
#
# Same shape as run_dose_sweep.slurm.sh. It resolves the variant selector to a
# targets glob and hands over to run_workflow.slurm.sh, which owns the Nextflow
# bootstrap. Running that script with bash rather than sbatch is deliberate: its
# own #SBATCH lines are comments to bash, and we are already in an allocation.
#
# ONE head job per submission, so the GPU concurrency bound applies once.
#
# What the control is: each target's receptor has its true-interface residues
# permuted at fixed composition before the run. reference_pdb is untouched, so the
# protected set, the restraints where they are on, and the receptor-aligned
# effector RMSD still reference the solved complex. A pose that still lands inside
# 5 A is therefore a false positive, and that is the point.
#
# Two arms, because the benchmark makes two claims. The restrained arm's control
# tests whether a pocket and contact block place the effector correctly whatever
# the receptor sequence is. The unrestrained arm's control tests whether forbidding
# the competing surface is by itself enough to produce the right pose. They fail
# for different reasons, so neither substitutes for the other.
#
# The tree is experiments/interface-ablation/, generated by
# scripts/make_ablation_controls.py. It is deliberately separate from
# experiments/benchmarking/, and this script globs only the ablation tree, so no
# benchmark run can be touched. A target that already holds run/ is skipped by
# Nextflow's -resume rather than overwritten.
#
# Sizing. Per-task cost under the workflow is ~350 s, not the ~100 s of the old
# single-job runner, because each task pays its own container start and model
# load. That is the same figure run_dose_sweep.slurm.sh uses, and for the same
# reason the committed benchmark's run_one_runtime_sec.txt must not be used here.
#
#   variant                  configs   ~predictions   ~GPU-hours   ~wall at 26
#   smoke_*                        2         14              1.4        ~0.3 h
#   scrambled_restrained          18       ~1150            112         ~4.5 h
#   scrambled_unrestrained        18       ~1150            112         ~4.5 h
#   all                           40       ~2314            225         ~9 h
#
# The per-variant prediction count assumes no target short-circuits, since an
# ablated receptor should not pose correctly from its cold start. A target that
# does short-circuit costs 3 predictions instead of ~64, and is itself a result.
#
# GPU concurrency is params.max_gpu_jobs in nextflow.config, applied as maxForks
# on the gpu label. Lower it on a busy weekday:
#
#   sbatch scripts/run_ablation_controls.slurm.sh scrambled --max_gpu_jobs 16
#
# If it dies partway, resubmit the identical command. run_workflow.slurm.sh
# always passes -resume, so finished targets are skipped.
# ─────────────────────────────────────────────────────────────────────────────

set -euo pipefail

SELECTOR="${1:-}"
shift || true

VARIANTS="scrambled_restrained scrambled_unrestrained \
smoke_scrambled_restrained smoke_scrambled_unrestrained"

if [ -z "${SELECTOR}" ]; then
    echo "ERROR: pass a variant selector." >&2
    echo "Use all, or one of: ${VARIANTS}" >&2
    exit 1
fi

REPO_DIR="${NEGSTEER_REPO_DIR:-${SLURM_SUBMIT_DIR:-}}"
if [ -z "${REPO_DIR}" ] || [ ! -f "${REPO_DIR}/main.nf" ]; then
    REPO_DIR="/hpc-home/jowillia/receptor_design/structure-negative-steering"
fi
if [ ! -f "${REPO_DIR}/main.nf" ]; then
    echo "ERROR: no main.nf under ${REPO_DIR}. Submit from the repo root." >&2
    exit 1
fi

ABL_DIR="${REPO_DIR}/experiments/interface-ablation"
if [ ! -d "${ABL_DIR}" ]; then
    echo "ERROR: no ${ABL_DIR}. Generate it with scripts/make_ablation_controls.py." >&2
    exit 1
fi

# ── Resolve the selector ─────────────────────────────────────────────────────
case "${SELECTOR}" in
    all)
        GLOB="experiments/interface-ablation/*/*/config.yml"
        LABEL="every variant"
        ;;
    scrambled_restrained|scrambled_unrestrained|smoke_scrambled_restrained|smoke_scrambled_unrestrained)
        if [ ! -d "${ABL_DIR}/${SELECTOR}" ]; then
            echo "ERROR: variant ${SELECTOR} not generated under ${ABL_DIR}." >&2
            echo "Run: python3 scripts/make_ablation_controls.py --variant ${SELECTOR}" >&2
            exit 1
        fi
        GLOB="experiments/interface-ablation/${SELECTOR}/*/config.yml"
        LABEL="variant ${SELECTOR}"
        ;;
    *)
        echo "ERROR: unknown selector '${SELECTOR}'." >&2
        echo "Use all, or one of: ${VARIANTS}. Available:" >&2
        (cd "${ABL_DIR}" && ls -d */ 2>/dev/null | grep -v '^references/' | sed 's|/$||; s/^/  /') >&2
        exit 1
        ;;
esac

# shellcheck disable=SC2086
N_CONFIGS=$(ls -1 ${REPO_DIR}/${GLOB} 2>/dev/null | wc -l | tr -d ' ')
if [ "${N_CONFIGS}" -eq 0 ]; then
    echo "ERROR: ${GLOB} matched no configs under ${REPO_DIR}." >&2
    exit 1
fi

# Every config in this tree must actually carry an ablation. A control that
# silently ran with the native sequence would look like a benchmark result.
# shellcheck disable=SC2086
MISSING=$(grep -LE '^interface_ablation:[[:space:]]*"(alanine|scrambled)"' \
    ${REPO_DIR}/${GLOB} 2>/dev/null || true)
if [ -n "${MISSING}" ]; then
    echo "ERROR: these configs carry no interface_ablation, so they are not controls:" >&2
    echo "${MISSING}" | sed 's/^/  /' >&2
    exit 1
fi

# The arm in the directory name must match the constraints toggle, or the control
# is the control for the other arm. Checked per config, since `all` spans both.
for cfg in ${REPO_DIR}/${GLOB}; do
    case "${cfg}" in
        */interface-ablation/*_unrestrained/*) WANT="false" ;;
        */interface-ablation/*_restrained/*)   WANT="true"  ;;
        *) echo "ERROR: ${cfg} is in no recognised arm directory." >&2; exit 1 ;;
    esac
    if ! grep -qE "^negsteer_boltz_constraints:[[:space:]]+${WANT}\b" "${cfg}"; then
        echo "ERROR: ${cfg} wants negsteer_boltz_constraints ${WANT} for its arm." >&2
        exit 1
    fi
done

echo "============================================================"
echo "Interface-ablation controls"
echo "============================================================"
echo "Selector:  ${SELECTOR}  (${LABEL})"
echo "Targets:   ${GLOB}"
echo "Configs:   ${N_CONFIGS}"
echo "Job:       ${SLURM_JOB_ID:-none}"
echo "Date:      $(date)"
echo "============================================================"
echo

exec bash "${REPO_DIR}/scripts/run_workflow.slurm.sh" "${GLOB}" "$@"
